
[System.Serializable]
public class Item
{
    public string itemName; // Название предмета
    public int level; // Уровень предмета
    public float damage; // Урон, наносимый предметом
    public float cooldown; // Время перезарядки предмета
    public float multiplier; // Множитель урона
    public string imagePath; // Локальный путь к файлу изображения
}